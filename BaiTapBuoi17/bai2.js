function getElectricityBill(kwh) {
    if (kwh <= 50) {
        console.log(`${kwh} * 1678 = ${kwh * 1678}`)
    }
        else if (kwh <= 100) {
        console.log(`(50 * 1678) + (${kwh - 50} * 1734) = ${(50 * 1678) + ((kwh - 50) * 1734)}`);
    }
        else if (kwh <= 200) {
            console.log(`(50 * 1678) + (50 * 1734) + (${kwh - 100} * 2014) = ${(50 * 1678) + (50 * 1734) + ((kwh - 100) * 2014)}`);
    }
        else if (kwh <= 300) {
            console.log(`(50 * 1678) + (50 * 1734) + (100 * 2014) + (${kwh -200} * 2536) = ${(50 * 1678) + (50 * 1734) + (100 * 2014) + ((kwh -200) * 2536)}`);
    }
        else if (kwh <= 400) {
            console.log(`(50 * 1678) + (50 * 1734) + (100 * 2014) + (200 * 2536) + (${kwh -300} * 2834) = ${(50 * 1678) + (50 * 1734) + (100 * 2014) + (200 * 2536) + ((kwh - 300) * 2834)}`)
    }
        else if (kwh > 400) {
            console.log(`(50 * 1678) + (50 * 1734) + (100 * 2014) + (200 * 2536) + (300 * 2834) + (${kwh - 400} * 2927) = ${(50 * 1678) + (50 * 1734) + (100 * 2014) + (200 * 2536) + (300 * 2834) + ((kwh - 400) * 2927)}`);
    }
}
getElectricityBill(70);
getElectricityBill(120);